# 3) 画图：0/1 均值条形图 + ΔP 图
# =========================================================
def plot_switch_summary(per_dataset, pooled, title_prefix=""):
    ok = per_dataset[per_dataset["ok"] == True].copy()
    if ok.empty:
        print("No valid datasets for plotting.")
        return

    # ---- 图1：每个数据集的 mean0/mean1 ----
    fig, ax = plt.subplots(figsize=(12, 6))

    x = np.arange(ok.shape[0])
    width = 0.35

    ax.bar(x - width/2, ok["mean0"].values, width, label="state=0 mean(P)")
    ax.bar(x + width/2, ok["mean1"].values, width, label="state=1 mean(P)")

    ax.set_xticks(x)
    ax.set_xticklabels([f"D{int(d)}" for d in ok["dataset"].values])
    ax.set_xlabel("Dataset")
    ax.set_ylabel("Mean battery_power (raw)")
    ax.set_title(f"{title_prefix} mean(P) at state=0 vs 1 (per dataset)")
    ax.grid(True, linestyle="--", alpha=0.4)
    ax.legend()

    # 你喜欢把 y 轴翻过来（更负=更耗电）
    ax.invert_yaxis()
    plt.tight_layout()
    plt.show()

    # ---- 图2：每个数据集的 ΔP（直觉版：正数=功耗增加）----
    fig, ax = plt.subplots(figsize=(12, 6))
    ax.bar(x, ok["delta_consumption"].values)
    ax.set_xticks(x)
    ax.set_xticklabels([f"D{int(d)}" for d in ok["dataset"].values])

    ax.set_xlabel("Dataset")
    ax.set_ylabel("ΔP (consumption) = -(mean1-mean0)  (positive => more power)")
    ax.set_title(f"{title_prefix} estimated GPS power increment per dataset")
    ax.grid(True, linestyle="--", alpha=0.4)

    # 这里不要 invert（因为我们已经转成“正数表示增加”）
    plt.tight_layout()
    plt.show()

    # ---- pooled 输出 ----
    if pooled is not None:
        print("\n[POOLED ESTIMATE]")
        print(f"switch_col: {pooled['switch_col']}")
        print(f"datasets used: {pooled['n_datasets_used']}")
        print(f"pooled delta_raw = mean1-mean0: {pooled['pooled_delta_raw']:.6f}")
        print(f"pooled delta_consumption = -(mean1-mean0): {pooled['pooled_delta_consumption']:.6f}")


