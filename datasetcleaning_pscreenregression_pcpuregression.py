# 4) 一键跑：gps_status + gps_activity
# =========================================================
def run_pgps_module(mcm_data_filtered_list, use_control=True):
    # ---- gps_status ----
    control_cols_status = CONTROL_COLS_BASE + [GPS_ACTIVITY_COL]  # activity 也作为控制变量固定住
    per_status, pooled_status = estimate_switch_delta(
        mcm_data_filtered_list,
        switch_col=GPS_STATUS_COL,
        control_cols=control_cols_status,
        use_control=use_control
    )
    print("\n=== gps_status summary (per dataset) ===")
    print(per_status)

    plot_switch_summary(per_status, pooled_status, title_prefix="GPS_STATUS")

    # ---- gps_activity ----
    control_cols_activity = CONTROL_COLS_BASE + [GPS_STATUS_COL]  # status 也作为控制变量固定住
    per_act, pooled_act = estimate_switch_delta(
        mcm_data_filtered_list,
        switch_col=GPS_ACTIVITY_COL,
        control_cols=control_cols_activity,
        use_control=use_control
    )
    print("\n=== gps_activity summary (per dataset) ===")
    print(per_act)

    plot_switch_summary(per_act, pooled_act, title_prefix="GPS_ACTIVITY")

    # ---- 最终 PGPS 参数（用 pooled）----
    # 直觉版参数：正数 = “开启带来功耗增加”
    alpha_status = None if pooled_status is None else pooled_status["pooled_delta_consumption"]
    alpha_act    = None if pooled_act is None else pooled_act["pooled_delta_consumption"]

    print("\n==============================")
    print("FINAL PGPS MODEL (recommended)")
    print("==============================")
    print("Let I{·} be the indicator function.")
    print("PGPS(t) = α_status * I{gps_status(t)=1} + α_activity * I{gps_activity(t)=1}")
    print("where α_status and α_activity are estimated by conditional mean differences.")
    print("")
    print(f"α_status   = {alpha_status}  (positive => more power when status=1)")
    print(f"α_activity = {alpha_act}     (positive => more power when activity=1)")

    return {
        "per_status": per_status, "pooled_status": pooled_status,
        "per_activity": per_act, "pooled_activity": pooled_act,
        "alpha_status": alpha_status, "alpha_activity": alpha_act
    }


