import numpy as np
from scipy.optimize import curve_fit

def f_log(b, A, C, b0):
    return A + C*np.log(b + b0)

def fit_log_model(b, p, w=None, b0_min=1e-6):
    b = np.asarray(b, float); p = np.asarray(p, float)
    if w is None:
        w = np.ones_like(p)
    else:
        w = np.asarray(w, float)

    A0 = np.sum(w*p)/np.sum(w)
    C0 = 0.1
    b0_0 = max(b0_min, 0.1*(np.max(b)-np.min(b)+1e-9))
    p0 = [A0, C0, b0_0]
    lower = [-np.inf, -np.inf, b0_min]
    upper = [ np.inf,  np.inf, np.inf]

    sigma = 1.0/np.sqrt(np.maximum(w, 1e-12))
    popt, _ = curve_fit(
        f_log, b, p, p0=p0, bounds=(lower, upper),
        sigma=sigma, absolute_sigma=False, maxfev=200000
    )
    A, C, b0 = popt
    return A, C, b0

def eval_metrics(y, yhat, w=None):
    y = np.asarray(y); yhat = np.asarray(yhat)
    err = y - yhat
    if w is None:
        rmse = np.sqrt(np.mean(err**2))
        mae = np.mean(np.abs(err))
    else:
        w = np.asarray(w, float)
        rmse = np.sqrt(np.sum(w*err**2)/np.sum(w))
        mae = np.sum(w*np.abs(err))/np.sum(w)
    medae = np.median(np.abs(err))
    return rmse, mae, medae

def kfold_log(b, p, K=5, seed=0, w=None):
    b = np.asarray(b, float); p = np.asarray(p, float)
    if w is not None:
        w = np.asarray(w, float)

    rng = np.random.default_rng(seed)
    idx = np.arange(len(b))
    rng.shuffle(idx)
    folds = np.array_split(idx, K)

    rows = []
    for k in range(K):
        te = folds[k]
        tr = np.setdiff1d(idx, te)

        w_tr = None if w is None else w[tr]
        w_te = None if w is None else w[te]

        A, C, b0 = fit_log_model(b[tr], p[tr], w=w_tr)
        yhat_tr = f_log(b[tr], A, C, b0)
        yhat_te = f_log(b[te], A, C, b0)

        rmse_tr, mae_tr, medae_tr = eval_metrics(p[tr], yhat_tr, w=w_tr)
        rmse_te, mae_te, medae_te = eval_metrics(p[te], yhat_te, w=w_te)

        rows.append({
            "fold": k, "A": A, "C": C, "b0": b0,
            "train_rmse": rmse_tr, "test_rmse": rmse_te,
            "train_mae": mae_tr, "test_mae": mae_te,
            "train_medae": medae_tr, "test_medae": medae_te,
        })
    return rows

