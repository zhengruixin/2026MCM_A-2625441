import numpy as np
import matplotlib.pyplot as plt

# 如果你装了 scipy（一般都有），用它做非线性拟合更稳
try:
    from scipy.optimize import curve_fit
    SCIPY_OK = True
except Exception:
    SCIPY_OK = False

# =========================
# 1) Log model: p = A + C * log(b + b0)
# =========================
def f_log(b, A, C, b0):
    b = np.asarray(b, float)
    return A + C * np.log(b + b0)

def fit_log_model(b, p, w=None, b0_min=1e-6):
    """
    拟合 log: p = A + C log(b+b0)
    返回 dict: params, rmse, r2, aic, yhat
    """
    b = np.asarray(b, float)
    p = np.asarray(p, float)
    if b.shape != p.shape:
        raise ValueError("b and p must have the same shape.")

    # 权重（可选）：w 越大越重要
    if w is None:
        w = np.ones_like(p, float)
    else:
        w = np.asarray(w, float)
        if w.shape != p.shape:
            raise ValueError("w must have same shape as p.")
        if np.any(w < 0) or np.sum(w) <= 0:
            raise ValueError("weights must be non-negative and sum > 0.")

    # 过滤无效点：b+b0 必须 > 0
    # b0 是要拟合的，所以这里只先过滤 b 非常极端的情况
    mask = np.isfinite(b) & np.isfinite(p)
    b = b[mask]; p = p[mask]; w = w[mask]

    if len(b) < 6:
        raise ValueError("Too few points for fitting (need >= 6).")

    # 初值：A 取加权均值；C 取一个小量；b0 取让 b+b0>0 的正数
    A0 = np.sum(w * p) / np.sum(w)
    C0 = 0.1
    b0_0 = max(b0_min, 0.1 * (np.max(b) - np.min(b) + 1e-9))
    p0 = [A0, C0, b0_0]

    # 参数约束：b0 > 0 防止 log 定义域问题
    lower = [-np.inf, -np.inf, b0_min]
    upper = [ np.inf,  np.inf, np.inf]

    if SCIPY_OK:
        # curve_fit 不支持直接权重，但支持 sigma；最小化 sum(((y-f)/sigma)^2)
        # 设 sigma = 1/sqrt(w) => 等价于加权最小二乘
        sigma = 1.0 / np.sqrt(np.maximum(w, 1e-12))

        popt, pcov = curve_fit(
            f_log, b, p,
            p0=p0, bounds=(lower, upper),
            sigma=sigma, absolute_sigma=False,
            maxfev=200000
        )
        A, C, b0 = popt
    else:
        # 没有 scipy 的 fallback：固定 b0 网格搜索 + 线性回归 A,C
        # （能跑但更粗糙）
        b0_candidates = np.linspace(b0_0 * 0.1, b0_0 * 10, 80)
        best = None
        for b0 in b0_candidates:
            x = np.log(b + b0)
            X = np.column_stack([np.ones_like(x), x])
            Xw = X * w[:, None]
            beta = np.linalg.lstsq(X.T @ Xw, X.T @ (w * p), rcond=None)[0]
            A, C = beta
            yhat = A + C * x
            sse = np.sum(w * (p - yhat) ** 2)
            if best is None or sse < best["sse"]:
                best = {"A": A, "C": C, "b0": b0, "sse": sse}
        A, C, b0 = best["A"], best["C"], best["b0"]

    # 预测与指标（加权）
    yhat = f_log(b, A, C, b0)
    resid = p - yhat
    sse = np.sum(w * resid**2)

    # 加权 RMSE
    rmse = np.sqrt(sse / np.sum(w))

    # 加权 R2
    pbar = np.sum(w * p) / np.sum(w)
    sst = np.sum(w * (p - pbar) ** 2)
    r2 = 1.0 - (sse / sst if sst > 0 else np.nan)

    # AIC（用 n 近似）
    n = len(p)
    k_params = 3  # A, C, b0
    aic = n * np.log((sse / n) + 1e-12) + 2 * k_params

    return {
        "A": float(A), "C": float(C), "b0": float(b0),
        "rmse": float(rmse), "r2": float(r2), "aic": float(aic),
        "b_used": b, "p_used": p, "w_used": w, "yhat_used": yhat
    }

